import type { Config, Report } from './types.js'

const f = (x: number | null) => (x === null ? '-' : x.toFixed(2))

function kindCounts(d: Record<string, number>, order: string[]): string {
  return order.map((k) => String(d[k] ?? 0)).join('/')
}

/** Shortest unique prefixes of the kinds, so the column header stays readable for any kinds. */
function abbreviations(order: string[]): Record<string, string> {
  const out: Record<string, string> = {}
  for (const k of order) {
    let n = 3
    while (n < k.length && order.some((o) => o !== k && o.startsWith(k.slice(0, n)))) n++
    out[k] = k.slice(0, n)
  }
  return out
}

/** The Markdown report. Deterministic: two runs on one input give the same bytes. */
export function renderMarkdown(report: Report, cfg: Config): string {
  const order = report.kinds
  const abbr = abbreviations(order)
  const short = (k: string) => abbr[k] ?? k
  const head = order.map(short).join('/')
  const s = report.summary
  const flt = report.filter
  const weightsTxt = order.map((k) => `${k} ${cfg.relationships.weights[k]}`).join(', ')
  const filterTxt = flt.status
    ? `\`--status ${flt.status.join(',')}\`: only relationships tagged ${flt.status.join(' or ')} are scored (${flt.scored} of ${flt.modelled}).`
    : `none. All ${flt.modelled} relationships are scored.`

  const L: string[] = [
    `# Budget report: ${report.project}`,
    '',
    'Generated by `likec4-budgets`; do not edit by hand.',
    '',
    `Filter: ${filterTxt}`,
    '',
    `Status: **${report.status}**. ${s.units} units, ${s.entities} entities, ${s.externals} externals, ` +
      `${s.relationships} relationships between units, ${s.externalRelationships} from externals, ` +
      `${s.violations} budget violations, ${s.warnings} warnings, ${s.modelErrors} model errors.`,
    '',
    `Counts in \`${head}\` order. Ce knows, Ca known by, I = Ce/(Ca+Ce), W-out = weighted outward coupling ` +
      `(weights ${weightsTxt}), W/ent = W-out per entity owned, Coh = cohesion (shown for groups only).`,
    '',
  ]

  for (const [dim, rows] of Object.entries(report.rollups)) {
    L.push(
      `## By ${dim}`, '',
      `| ${dim} | Units | Entities | Internal | Out (${head}) | In (${head}) | Ce | Ca | I | Breadth | Depth | W-out | W/ent | Coh |`,
      '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|',
    )
    for (const [value, m] of Object.entries(rows)) {
      L.push(
        `| ${value} | ${m.units} | ${m.entities} | ${m.internal} | ${kindCounts(m.out, order)} | ${kindCounts(m.in, order)} | ` +
          `${m.ce} | ${m.ca} | ${f(m.instability)} | ${m.breadth} | ${m.depth ?? '-'} | ${m.weightedOut} | ${f(m.weightedPerEntity)} | ${f(m.cohesion)} |`,
      )
    }
    L.push('')
  }
  for (const t of report.groupTotals) {
    L.push(
      `${t.rule}: weighted outward coupling of ${t.subject} in total ${t.weightedTotal}. ` +
        `Of it, ${t.weightedTotal - t.weightedLeaving} is between its units and ${t.weightedLeaving} leaves the group (budget ${t.max}).`,
      '',
    )
  }

  const dims = Object.keys(report.rollups)
  L.push(
    '## Units', '',
    `| Unit | ${dims.join(' | ')} | Kind | Ent | Int | Out (${head}) | In (${head}) | Ce | Ca | I | Breadth | Depth | W-out | W/ent |`,
    `|---|${'---|'.repeat(dims.length)}---|---|---|---|---|---|---|---|---|---|---|---|`,
  )
  const unitList = Object.values(report.units).sort((a, b) => {
    const ka = dims.map((d) => a.attributes[d] ?? '?').join('\u0000')
    const kb = dims.map((d) => b.attributes[d] ?? '?').join('\u0000')
    return ka < kb ? -1 : ka > kb ? 1 : a.id < b.id ? -1 : a.id > b.id ? 1 : 0
  })
  for (const m of unitList) {
    L.push(
      `| ${m.id} | ${dims.map((d) => m.attributes[d] ?? '?').join(' | ')} | ${m.kind} | ${m.entityIds.length} | ${m.internal} | ` +
        `${kindCounts(m.out, order)} | ${kindCounts(m.in, order)} | ${m.ce} | ${m.ca} | ${f(m.instability)} | ${m.breadth} | ${m.depth ?? '-'} | ` +
        `${m.weightedOut} | ${f(m.weightedPerEntity)} |`,
    )
  }
  L.push('')

  L.push('## Budget violations', '')
  if (report.violations.length) {
    L.push('| Rule | Where | Budget | Observed |', '|---|---|---|---|')
    for (const v of report.violations) L.push(`| ${v.rule} | \`${v.subject}\` | \`${v.budget}\` | ${v.observed} |`)
  } else L.push('None.')
  L.push('')

  L.push('## Model errors', '')
  if (report.modelErrors.length) {
    L.push('| Rule | Where | Problem |', '|---|---|---|')
    for (const e of report.modelErrors) L.push(`| ${e.rule} | \`${e.subject}\` | ${e.message} |`)
  } else L.push('None.')
  L.push('')

  L.push('## Warnings', '', 'Reported, never a failure.', '')
  for (const w of cfg.warnings ?? []) {
    L.push(`### ${w.id}: ${w.description}`, '')
    if (w.enabled === false) {
      L.push('Off in the config.', '')
      continue
    }
    const mine = report.warnings.filter((x) => x.rule === w.id)
    L.push(...(mine.length ? mine.map((x) => `- \`${x.subject}\`: ${x.detail}`) : ['None.']), '')
  }

  L.push('## Merge candidates', '', 'Pairs of units that share more relationships with each other than either has inside.', '')
  if (report.mergeCandidates.length) {
    L.push('| Pair | Shared | Internal A | Internal B |', '|---|---|---|---|')
    for (const m of report.mergeCandidates) L.push(`| \`${m.a}\`, \`${m.b}\` | ${m.shared} | ${m.internalA} | ${m.internalB} |`)
  } else L.push('None.')
  L.push('')

  L.push(
    '## Externals', '',
    'Relationships that start in an external are counted in no budget and no coupling figure. Per external, what it knows outside itself, by kind.',
    '',
  )
  const ext = Object.values(report.externals)
  if (ext.length) {
    for (const c of ext) {
      L.push(
        `### \`${c.id}\``, '',
        `${c.entityIds.length} entities, ${c.relationships} relationships, ${c.internal} of them inside the external.`, '',
      )
      const known = order.filter((k) => (c.knows[k] ?? []).length > 0)
      L.push(...(known.length ? known.map((k) => `- ${k}: ${c.knows[k]!.map((t) => `\`${t}\``).join(', ')}`) : ['Knows nothing.']), '')
    }
  } else L.push('None.', '')

  L.push('## Call cycles', '')
  L.push(...(report.cycles.length ? report.cycles.map((c) => `- ${c.join(' , ')}`) : ['None.']), '')

  const ids = Object.keys(report.units)
  L.push(
    '## Knowledge matrix', '',
    `Row knows column. Cell is the strongest kind used (${order.map((k) => `${short(k)} = ${k}`).join(', ')}). Empty: knows nothing.`,
    '',
  )
  if (ids.length) {
    L.push(`| knows \\ known | ${ids.join(' | ')} |`, `|---|${'---|'.repeat(ids.length)}`)
    for (const r of ids) {
      const row = report.matrix[r] ?? {}
      L.push(`| ${r} | ${ids.map((c) => (row[c] ? short(row[c]!) : '')).join(' | ')} |`)
    }
  }
  L.push('')
  return L.join('\n')
}
